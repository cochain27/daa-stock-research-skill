"""组合验证：超卖深度/量比等新因子 + 2-4只/天 + 转化率最高
只读研究，不改策略代码。
"""
import pandas as pd

df = pd.read_csv('data/低位池_入池事件_20260923.csv')
df['入池日'] = pd.to_datetime(df['入池日'])

def v6():
    return (
        (df['成交额亿'] <= 6) & (df['位置'] <= 0.40) & (df['距高%'] <= -25) &
        (df['MA20乖离%'] >= -5) & (df['20日振幅%'] < 25) & (df['量比'] <= 2.0)
    )

def report(mask, label, min_n=60):
    sub = df[mask]
    n = len(sub)
    if n < min_n:
        print(f'{label:46s} 事件={n:4d}（样本不足）')
        return None
    daily = sub.groupby('入池日').size().mean()
    r5 = (sub['5日内启动'] == 1).mean() * 100
    r10 = (sub['10日内启动'] == 1).mean() * 100
    r60 = (sub['60日内启动'] == 1).mean() * 100
    t5 = sub['入池直接T5%'].mean()
    t5_pos = (sub['入池直接T5%'] > 0).mean() * 100
    st5 = sub['启动后T5%'].mean()
    print(f'{label:46s} 事件={n:5d} 每天={daily:4.1f} 5日启动={r5:5.1f}% 10日启动={r10:5.1f}% 60日启动={r60:5.1f}% 入池T5={t5:+5.2f}% 胜率={t5_pos:4.1f}% 启动后T5={st5:+5.2f}%')
    return dict(n=n, daily=daily, r5=r5, r10=r10, t5=t5, st5=st5)

print('=== 基线 ===')
report(v6(), 'V6\' 全条件（现状）')

print()
print('=== 候选组合（V6\' 基础上叠加新因子） ===')
combs = [
    ('超卖深度≥0.4', df['超卖深度'] >= 0.4),
    ('量比1.2-2.0', (df['量比'] >= 1.2) & (df['量比'] <= 2.0)),
    ('量比1.2-2.0 + 振幅<15', (df['量比'] >= 1.2) & (df['量比'] <= 2.0) & (df['20日振幅%'] < 15)),
    ('超卖深度≥0.4 + 量比1.2-2.0', (df['超卖深度'] >= 0.4) & (df['量比'] >= 1.2) & (df['量比'] <= 2.0)),
    ('超卖深度≥0.4 + 振幅<15', (df['超卖深度'] >= 0.4) & (df['20日振幅%'] < 15)),
    ('超卖深度≥0.4 + 额3-6亿', (df['超卖深度'] >= 0.4) & (df['成交额亿'] >= 3)),
    ('超卖深度≥0.4 + 位置0.25-0.40', (df['超卖深度'] >= 0.4) & (df['位置'] >= 0.25)),
    ('量比1.2-2.0 + 乖离-3~3', (df['量比'] >= 1.2) & (df['量比'] <= 2.0) & (df['MA20乖离%'] >= -3) & (df['MA20乖离%'] <= 3)),
    ('量比1.2-2.0 + 5日涨幅<0', (df['量比'] >= 1.2) & (df['量比'] <= 2.0) & (df['5日涨幅%'] < 0)),
    ('超卖深度0.3-0.5', (df['超卖深度'] >= 0.3) & (df['超卖深度'] <= 0.5)),
    ('超卖深度0.3-0.5 + 量比1.2-2.0', (df['超卖深度'] >= 0.3) & (df['超卖深度'] <= 0.5) & (df['量比'] >= 1.2) & (df['量比'] <= 2.0)),
    ('5日涨幅-10~0', (df['5日涨幅%'] >= -10) & (df['5日涨幅%'] <= 0)),
    ('5日涨幅-10~0 + 量比1.2-2.0', (df['5日涨幅%'] >= -10) & (df['5日涨幅%'] <= 0) & (df['量比'] >= 1.2) & (df['量比'] <= 2.0)),
]
for label, cond in combs:
    report(v6() & cond, label)
