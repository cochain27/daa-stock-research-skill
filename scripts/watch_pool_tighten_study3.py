# -*- coding: utf-8 -*-
"""触发端转化率评估：入池 → 触发（量比≥2 + 涨幅≥10% + 破MA20 + 额4-16亿）→ 盈利
用事件文件：入池后 5/10 日内是否启动 + 启动后 T5 表现，估算观察池→触发的完整漏斗
只读研究，不改策略代码。
"""
import pandas as pd

df = pd.read_csv('data/低位池_入池事件_20260923.csv')
df['入池日'] = pd.to_datetime(df['入池日'])
N_DAYS = df['入池日'].nunique()

def v6():
    return (
        (df['成交额亿'] <= 6) & (df['位置'] <= 0.40) & (df['距高%'] <= -25) &
        (df['MA20乖离%'] >= -5) & (df['20日振幅%'] < 25) & (df['量比'] <= 2.0)
    )

def full_report(mask, label):
    sub = df[mask]
    n = len(sub)
    if n < 50:
        print(f'{label:40s} 事件={n:4d}（样本不足）')
        return
    daily = sub.groupby('入池日').size().mean()
    r5 = (sub['5日内启动'] == 1).mean() * 100
    r10 = (sub['10日内启动'] == 1).mean() * 100
    r60 = (sub['60日内启动'] == 1).mean() * 100
    # 触发端近似：启动日当天 = 触发（量比≥2+涨幅），用启动后T5看盈利
    trig = sub[sub['5日内启动'] == 1]
    # 入池直接T5（不管启不启动）
    t5 = sub['入池直接T5%'].mean()
    t5_pos = (sub['入池直接T5%'] > 0).mean() * 100
    # 启动子集表现
    st5 = sub['启动后T5%'].mean()
    st5_pos = (sub['启动后T5%'] > 0).mean() * 100
    print(f'{label:40s} 事件={n:5d} 每天={daily:4.1f} 5日启动={r5:5.1f}% 10日启动={r10:5.1f}% 60日启动={r60:5.1f}%')
    print(f'{"":40s}   入池T5={t5:+5.2f}% 胜率={t5_pos:4.1f}% | 启动后T5={st5:+5.2f}% 胜率={st5_pos:4.1f}%')
    print(f'{"":40s}   每日触发估算(5日启动×每天): {daily*r5/100:.2f} 只/天 | 每周触发: {daily*r5/100*5:.1f} 只/周')

print('=== 触发端转化漏斗（观察池 → 启动/触发） ===')
print('触发端条件：量比≥2 + 涨幅≥10% + 破MA20 + 额4-16亿（事件文件以 5日内启动 近似）')
print()

print('--- 基线 V6\' ---')
full_report(v6(), 'V6\' 全条件（现状，每天3.5只）')

print()
print('--- 候选收紧档 ---')
for label, m in [
    ('振幅<15', v6() & (df['20日振幅%'] < 15)),
    ('振幅<20', v6() & (df['20日振幅%'] < 20)),
    ('额≤4亿', v6() & (df['成交额亿'] <= 4)),
    ('乖离≥-2', v6() & (df['MA20乖离%'] >= -2)),
    ('乖离≥0', v6() & (df['MA20乖离%'] >= 0)),
    ('5日量比≤1.0', v6() & (df['5日量比'] <= 1.0)),
    ('振幅<15+额≤4亿', v6() & (df['20日振幅%'] < 15) & (df['成交额亿'] <= 4)),
    ('振幅<15+乖离≥-2', v6() & (df['20日振幅%'] < 15) & (df['MA20乖离%'] >= -2)),
    ('振幅<15+额≤4亿+乖离≥-2', v6() & (df['20日振幅%'] < 15) & (df['成交额亿'] <= 4) & (df['MA20乖离%'] >= -2)),
    ('振幅<20+额≤4亿+乖离≥-2', v6() & (df['20日振幅%'] < 20) & (df['成交额亿'] <= 4) & (df['MA20乖离%'] >= -2)),
    ('振幅<15+乖离≥0+5日量比≤1.0', v6() & (df['20日振幅%'] < 15) & (df['MA20乖离%'] >= 0) & (df['5日量比'] <= 1.0)),
    ('额≤4亿+乖离≥-2', v6() & (df['成交额亿'] <= 4) & (df['MA20乖离%'] >= -2)),
]:
    full_report(m, label)
