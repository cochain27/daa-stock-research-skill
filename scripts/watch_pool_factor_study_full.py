# -*- coding: utf-8 -*-
"""低位观察池 全画像因子归因（V6' 基线内分桶）
只读事件文件，不碰任何生产代码。
基线 = V6' 全条件：额≤6亿 + pos60≤0.40 + 距高≤-25% + MA20乖离≥-5% + 振幅<25 + 量比≤2.0
指标：事件数 / 每天只数 / 5日启动率 / 10日启动率 / 入池直接T5% / 启动后T5%
"""
import pandas as pd

df = pd.read_csv("data/低位池_入池事件_20260923.csv", dtype={"代码": str})
df["入池日"] = pd.to_datetime(df["入池日"])

# ---- V6' 基线 ----
base = (
    (df["成交额亿"] <= 6)
    & (df["位置"] <= 0.40)
    & (df["距高%"] <= -25)
    & (df["MA20乖离%"] >= -5)
    & (df["20日振幅%"] < 25)
    & (df["量比"] <= 2.0)
)
B = df[base]
n_days = B["入池日"].nunique()
print(f"V6'基线: {len(B)} 事件 / {n_days} 天 / 每天 {len(B)/n_days:.1f} 只")
print(f"  5日启动 {B['5日内启动'].mean()*100:.1f}% | 10日启动 {B['10日内启动'].mean()*100:.1f}% | 入池T5 {B['入池直接T5%'].mean():+.2f}% | 启动后T5 {B[B['启动后T5%'].notna()]['启动后T5%'].mean():+.2f}% (n={B['启动后T5%'].notna().sum()})")
print()

def bucket(col, edges, labels=None, min_n=30):
    """对连续列分桶归因；min_n 为桶最小样本，过小标记不可信"""
    print(f"=== {col} ===")
    tmp = B.copy()
    tmp["_b"] = pd.cut(tmp[col], bins=edges, labels=labels, right=False)
    for b, g in tmp.groupby("_b", observed=True):
        n = len(g)
        if n < min_n:
            mark = "⚠️小样本"
        else:
            mark = ""
        daily = n / g["入池日"].nunique()
        r5 = g["5日内启动"].mean() * 100
        r10 = g["10日内启动"].mean() * 100
        t5 = g["入池直接T5%"].mean()
        st5 = g[g["启动后T5%"].notna()]["启动后T5%"].mean() if g["启动后T5%"].notna().sum() >= 10 else float("nan")
        sn = g["启动后T5%"].notna().sum()
        print(f"  {b}: n={n:4d} 每天{daily:4.1f} 5日启{r5:4.1f}% 10日启{r10:4.1f}% 入池T5{t5:+5.2f}% 启动后T5{st5:+.2f}%(n={sn}) {mark}")
    print()

# 事件文件自带的画像列
bucket("量能收缩", [-1e9, 0.5, 0.7, 0.85, 1.0, 1.5], ["<0.5", "0.5-0.7", "0.7-0.85", "0.85-1.0", "1.0-1.5"])
bucket("连续蓄势", [0, 3, 5, 8, 12, 999], ["0-3", "3-5", "5-8", "8-12", "12+"])
bucket("超卖龄", [-1, 5, 10, 15, 20, 999], ["<5", "5-10", "10-15", "15-20", "20+"])
bucket("超卖深度", [-1e9, 0.15, 0.25, 0.35, 0.5, 1e9], ["<0.15", "0.15-0.25", "0.25-0.35", "0.35-0.5", ">=0.5"])
bucket("距启动", [-1, 3, 5, 8, 12, 999], ["<3", "3-5", "5-8", "8-12", "12+"])
# 关键量价列（V6' 基线内再细分）
bucket("量比", [0, 0.5, 0.7, 0.9, 1.2, 1.6, 2.01], ["<0.5", "0.5-0.7", "0.7-0.9", "0.9-1.2", "1.2-1.6", "1.6-2.0"])
bucket("5日量比", [0, 0.6, 0.8, 1.0, 1.3, 999], ["<0.6", "0.6-0.8", "0.8-1.0", "1.0-1.3", "1.3+"])
bucket("5日涨幅%", [-30, -5, -2, 0, 2, 5, 30], ["<-5", "-5~-2", "-2~0", "0~2", "2~5", "5+"])
bucket("20日振幅%", [0, 10, 15, 18, 21, 25], ["<10", "10-15", "15-18", "18-21", "21-25"])
bucket("成交额亿", [0, 1, 2, 3, 4, 6], ["<1", "1-2", "2-3", "3-4", "4-6"])
bucket("位置", [0, 0.1, 0.2, 0.3, 0.4], ["<0.1", "0.1-0.2", "0.2-0.3", "0.3-0.4"])
bucket("距高%", [-60, -45, -35, -28, -25], ["<-45", "-45~-35", "-35~-28", "-28~-25"])
bucket("MA20乖离%", [-5, -3, -1, 0, 2, 5], ["-5~-3", "-3~-1", "-1~0", "0~2", "2~5"])
