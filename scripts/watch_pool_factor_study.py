"""因子归因：在 V6' 基线内，找能砍数量 + 提转化率的维度
只读研究，不改策略代码。
"""
import pandas as pd

df = pd.read_csv('data/低位池_入池事件_20260923.csv')
df['入池日'] = pd.to_datetime(df['入池日'])

def v6():
    return (
        (df['成交额亿'] <= 6) & (df['位置'] <= 0.40) & (df['距高%'] <= -25) &
        (df['MA20乖离%'] >= -5) & (df['20日振幅%'] < 25) & (df['量比'] <= 2.0)
    )

base = v6()
sub = df[base].copy()
print(f'V6\' 基线: {len(sub)} 事件, 每天 {sub.groupby("入池日").size().mean():.1f}')

def bucket(series, bins, labels, title):
    print(f'\n=== {title} ===')
    b = pd.cut(series, bins=bins, labels=labels, include_lowest=True)
    g = sub.groupby(b, observed=True)
    for name, grp in g:
        n = len(grp)
        if n < 40:
            continue
        daily = grp.groupby('入池日').size().mean()
        r5 = (grp['5日内启动'] == 1).mean() * 100
        r10 = (grp['10日内启动'] == 1).mean() * 100
        t5 = grp['入池直接T5%'].mean()
        st5 = grp['启动后T5%'].mean()
        print(f'  {str(name):12s} n={n:4d} 每天={daily:4.1f} 5日启动={r5:5.1f}% 10日启动={r10:5.1f}% 入池T5={t5:+5.2f}% 启动后T5={st5:+5.2f}%')

# 现有因子分桶（基线内）
bucket(sub['量能收缩'], [0, 0.8, 1.0, 1.2, 1.5, 9], ['<0.8', '0.8-1', '1-1.2', '1.2-1.5', '>1.5'], '量能收缩（<1=缩量）')
bucket(sub['连续蓄势'], [0, 1, 2, 3, 9], ['=1', '=2', '=3', '>3'], '连续蓄势天数')
bucket(sub['超卖龄'], [0, 15, 20, 24, 30], ['<15', '15-20', '20-24', '>24'], '超卖龄（超卖后交易日）')
bucket(sub['超卖深度'], [0, 0.2, 0.3, 0.4, 0.5, 1], ['<0.2', '0.2-0.3', '0.3-0.4', '0.4-0.5', '>0.5'], '超卖深度')
bucket(sub['MA20乖离%'], [-6, -3, 0, 3, 10], ['-5~-3', '-3~0', '0~3', '>3'], 'MA20乖离%（基线内已≥-5）')
bucket(sub['5日量比'], [0, 0.6, 0.8, 1.0, 1.2, 3], ['<0.6', '0.6-0.8', '0.8-1.0', '1.0-1.2', '>1.2'], '5日量比（基线已≤1.2）')
bucket(sub['位置'], [0, 0.15, 0.25, 0.35, 0.41], ['<0.15', '0.15-0.25', '0.25-0.35', '0.35-0.4'], '位置（基线内）')
bucket(sub['5日涨幅%'], [-30, -10, -5, 0, 5, 30], ['<-10', '-10~-5', '-5~0', '0~5', '>5'], '5日涨幅%')
bucket(sub['20日振幅%'], [0, 10, 15, 20, 25], ['<10', '10-15', '15-20', '20-25'], '20日振幅%（基线内）')
bucket(sub['成交额亿'], [0, 2, 3, 4, 6], ['<2', '2-3', '3-4', '4-6'], '成交额亿（基线内）')
bucket(sub['量比'], [0, 0.8, 1.2, 1.6, 2.1], ['<0.8', '0.8-1.2', '1.2-1.6', '1.6-2.0'], '量比（基线内）')
